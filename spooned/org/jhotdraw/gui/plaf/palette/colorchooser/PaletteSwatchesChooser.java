    @java.lang.Override
    public void updateChooser() {
        if ((updateRecursion++) == 0) {
            javax.swing.ListModel m = jList.getModel();
            java.awt.Color mc = getColorFromModel();
            if (mc != null) {
                int ma = mc.getAlpha();
                int mr = mc.getRed();
                int mg = mc.getGreen();
                int mb = mc.getBlue();
                int closestSquaredDistance = java.lang.Integer.MAX_VALUE;
                int closestIndex = -1;
                for (int i = 0, n = m.getSize(); i < n; i++) {
                    org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon item = ((org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon) (m.getElementAt(i)));
                    java.awt.Color ic = (item == null) ? null : item.getColor();
                    int squaredDistance;
                    if ((ic == null) || (ic.getAlpha() != ma)) {
                        squaredDistance = java.lang.Integer.MAX_VALUE;
                    } else {
                        squaredDistance = (((mr - ic.getRed()) * (mr - ic.getRed())) + ((mg - ic.getGreen()) * (mg - ic.getGreen()))) + ((mb - ic.getBlue()) * (mb - ic.getBlue()));
                    }
                    if (squaredDistance <= closestSquaredDistance) {
                        closestSquaredDistance = squaredDistance;
                        closestIndex = i;
                        if (squaredDistance == 0) {
                            break;
                        }
                    }
                }
                if (closestIndex == (-1)) {
                    jList.clearSelection();
                } else {
                    jList.setSelectedIndex(closestIndex);
                }
            }
        }
        updateRecursion--;
    }

