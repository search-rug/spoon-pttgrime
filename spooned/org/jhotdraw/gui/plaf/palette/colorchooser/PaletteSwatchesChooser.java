    private static final int HSB_COLORS_AS_RGB_COLUMN_COUNT = 12;

    static {
        // FIXME - Move this into a lazy initializer
        org.jhotdraw.color.HSBColorSpace hsbCS = org.jhotdraw.color.HSBColorSpace.getInstance();
        java.util.List<org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon> m = new java.util.ArrayList<>();
        org.jhotdraw.util.ResourceBundleUtil labels = org.jhotdraw.util.ResourceBundleUtil.getBundle("org.jhotdraw.gui.Labels");
        for (int s = 2; s <= 8; s += 2) {
            for (int h = 0; h < 12; h++) {
                java.awt.Color c = new java.awt.Color(hsbCS, new float[]{ h / 12.0F, s * 0.1F, 1.0F }, 1.0F);
                m.add(new org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon(c, labels.getFormatted("ColorChooser.colorSwatch.hsbComponents.toolTipText", (h * 360) / 12, s * 10, 100)));
            }
        }
        for (int b = 10; b >= 2; b -= 2) {
            for (int h = 0; h < 12; h++) {
                java.awt.Color c = new java.awt.Color(hsbCS, new float[]{ h / 12.0F, 1.0F, b * 0.1F }, 1.0F);
                m.add(new org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon(new java.awt.Color(hsbCS, new float[]{ h / 12.0F, 1.0F, b * 0.1F }, 1.0F), labels.getFormatted("ColorChooser.colorSwatch.hsbComponents.toolTipText", (h * 360) / 12, 100, b * 10)));
            }
        }
        m.add(new org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon(new java.awt.Color(0, true), labels.getToolTipTextProperty("ColorChooser.colorSwatch.noColor")));
        HSB_COLORS = java.util.Collections.unmodifiableList(m);
        m = new java.util.ArrayList<>();
        for (org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon ci : HSB_COLORS) {
            if (ci.getColor() == null) {
                m.add(new org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon(new java.awt.Color(0, true), labels.getToolTipTextProperty("ColorChooser.colorSwatch.noColor")));
            } else {
                java.awt.Color c = ci.getColor();
                m.add(new org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon(c, labels.getFormatted("ColorChooser.colorSwatch.rgbComponents.toolTipText", c.getRed(), c.getGreen(), c.getBlue())));
            }
        }
        HSB_COLORS_AS_RGB = java.util.Collections.unmodifiableList(m);
    }

