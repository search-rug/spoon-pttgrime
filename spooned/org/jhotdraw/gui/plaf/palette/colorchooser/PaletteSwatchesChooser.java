    @java.lang.Override
    protected void buildChooser() {
        initComponents();
        setUI(org.jhotdraw.gui.plaf.palette.PalettePanelUI.createUI(this));
        jList.setUI(((javax.swing.plaf.ListUI) (org.jhotdraw.gui.plaf.palette.PaletteListUI.createUI(jList))));
        java.lang.Object[] byRows = org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB.toArray();
        java.lang.Object[] byColumns = new java.lang.Object[byRows.length];
        for (int y = 0, my = byRows.length / org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB_COLUMN_COUNT; y < my; y++) {
            for (int x = 0; x < org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB_COLUMN_COUNT; x++) {
                if (((x * my) + y) < byColumns.length) {
                    byColumns[(x * my) + y] = byRows[(y * org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB_COLUMN_COUNT) + x];
                }
            }
        }
        byColumns[byColumns.length - 1] = byRows[byRows.length - 1];
        jList.setListData(byColumns);
        jList.setVisibleRowCount(org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB.size() / org.jhotdraw.gui.plaf.palette.colorchooser.PaletteSwatchesChooser.HSB_COLORS_AS_RGB_COLUMN_COUNT);
        jList.addListSelectionListener(new javax.swing.event.ListSelectionListener() {
            @java.lang.Override
            public void valueChanged(javax.swing.event.ListSelectionEvent e) {
                if ((updateRecursion++) == 0) {
                    org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon item = ((org.jhotdraw.gui.plaf.palette.colorchooser.ColorIcon) (jList.getSelectedValue()));
                    setColorToModel(item == null ? null : item.getColor());
                }
                updateRecursion--;
            }
        });
    }

